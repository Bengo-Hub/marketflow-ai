// Formats are the sizes the studio offers: landscape full HD (the default for video since
// 2026-11-19, so an ad plays full screen on laptops, desktops, tablets and phones held
// sideways), square, the 4:5 feed and 9:16 stories and reels.
var Formats = map[string]image.Point{
	"1920x1080": {1920, 1080},
	"1080x1080": {1080, 1080},
	"1080x1350": {1080, 1350},
	"1080x1920": {1080, 1920},
}

// FormatsText names the formats for error messages.
const FormatsText = "1920x1080, 1080x1080, 1080x1350 or 1080x1920"

// Landscape reports whether a format is wider than it is tall.
func Landscape(format string) bool {
	s, ok := Formats[format]
	return ok && s.X > s.Y
}

// layoutUnit is the length text, margins and the logo are sized from: the short side, so a
// landscape frame gets the same type sizes as the portrait frame of the same height, and the
// portrait and square formats keep the sizes they always had (their width is the short side).
func layoutUnit(w, h int) int { return min(w, h) }

// Overlay is the exact text and branding drawn on a poster. Prices, phone
// numbers and calls to action are never generated by an image model: they are
// drawn here, so they are always right.
type Overlay struct {
	Headline string
	Subline  string
	Price    string // shown as given, e.g. "KES 850"
	CTA      string // e.g. "Order on WhatsApp", drawn as words, never as a button
	// Contacts are the real ways to reach the business (WhatsApp, phone, website, email, a
	// product link), drawn with their icons under the call to action (contacts.go).
	Contacts []Contact
	Logo     image.Image
	Accent   color.RGBA // brand colour for the price chip, the icons and the CTA rule
	// LogoCorner pins the logo to LogoTopLeft or LogoTopRight; "" lets the compositor pick the
	// calmer top corner of the scene (the self-review asks for the other corner on a retry).
	LogoCorner string
	// Plate is how the logo is backed (style, opacity, brand tint): logo_plate.go.
	Plate PlateStyle
	// Strong draws a taller, darker band under the words (a layout retry for legibility).
	Strong bool
}

// Logo corners.
const (
	LogoTopLeft  = "top_left"
	LogoTopRight = "top_right"
)

var (
	fontsOnce     sync.Once
	boldTT, regTT *opentype.Font
	errFonts      error
	defaultAccent = color.RGBA{0x6d, 0x28, 0xd9, 0xff} // Codevertex purple
	bandAlpha     = uint8(0xd8)                        // darkest point of the text band
)

// The Go fonts (BSD licence) are compiled into x/image, so posters need no font
// files on disk.
func fonts() (*opentype.Font, *opentype.Font, error) {
	fontsOnce.Do(func() {
		if boldTT, errFonts = opentype.Parse(gobold.TTF); errFonts != nil {
			return
		}
		regTT, errFonts = opentype.Parse(goregular.TTF)
	})
	return boldTT, regTT, errFonts
}

func face(f *opentype.Font, size float64) (font.Face, error) {
	return opentype.NewFace(f, &opentype.FaceOptions{Size: size, DPI: 72, Hinting: font.HintingFull})
}

// ComposePoster scales the scene to cover the format, darkens the lower part
// for legibility and draws the logo, headline, subline, price and button.
func ComposePoster(scene image.Image, format string, o Overlay) (image.Image, error) {
	size, ok := Formats[format]
	if !ok {
		return nil, fmt.Errorf("media: unknown poster format %q", format)
	}
	canvas := image.NewRGBA(image.Rect(0, 0, size.X, size.Y))
	cover(canvas, scene)
	if err := drawOverlay(canvas, o); err != nil {
		return nil, err
	}
	return canvas, nil
}

// ComposeOverlay draws the same band, logo and text on a transparent canvas: the
// layer laid over a video so its words are exact (models redraw any text they are
// shown, so a clip is made from the clean scene and this goes on top).
func ComposeOverlay(format string, o Overlay) (*image.RGBA, error) {
	size, ok := Formats[format]
	if !ok {
		return nil, fmt.Errorf("media: unknown poster format %q", format)
	}
	canvas := image.NewRGBA(image.Rect(0, 0, size.X, size.Y))
	if err := drawOverlay(canvas, o); err != nil {
		return nil, err
	}
	return canvas, nil
}

// drawOverlay draws the legibility band, logo, headline, subline, price and
// button over whatever canvas already holds.
func drawOverlay(canvas *image.RGBA, o Overlay) error {
	bold, reg, err := fonts()
	if err != nil {
		return fmt.Errorf("media: fonts: %w", err)
	}
	if o.Accent.A == 0 {
		o.Accent = defaultAccent
	}
	W, H := canvas.Bounds().Dx(), canvas.Bounds().Dy()

	// A dark band over the lower 45%, fading in, so white text reads on any scene.
	bandStart, peak := H*55/100, float64(bandAlpha)
	if o.Strong {
		// A layout retry after the review found the words hard to read: a taller, darker band.
		bandStart, peak = H*42/100, 0xf2
	}
	for y := bandStart; y < H; y++ {
		t := float64(y-bandStart) / float64(H-bandStart)
		a := uint8(peak * min1(t*1.6))
		draw.Draw(canvas, image.Rect(0, y, W, y+1), image.NewUniform(color.RGBA{0, 0, 0, a}), image.Point{}, draw.Over)
	}

	U := layoutUnit(W, H)
	margin := U * 6 / 100
	if o.Logo != nil {
		// One logo helper for posters, motion posters, end cards and scene logos (logo_plate.go).
		info := analyseLogo(o.Logo)
		o.Logo = info.img
		placeLogo(canvas, info, logoCorner(canvas, o, margin, U), margin, U, o.Plate)
	}

	textW := W - 2*margin
	// Lay out bottom-up: the contacts, the call to action as words, then price, subline and
	// headline above it. Nothing is drawn as a button.
	y := H - margin
	if list := CleanContacts(o.Contacts); len(list) > 0 {
		y = drawContacts(canvas, reg, list, margin, y, textW, U, o.Accent)
		y -= H * 2 / 100
	}
	if cta := strings.TrimSpace(o.CTA); cta != "" {
		y = drawCTA(canvas, bold, cta, margin, y, textW, U, o.Accent)
		y -= H * 2 / 100
	}
	if price := strings.TrimSpace(o.Price); price != "" {
		y = drawChip(canvas, bold, price, margin, y, U, o.Accent)
		y -= H * 2 / 100
	}
	if sub := strings.TrimSpace(o.Subline); sub != "" {
		y = drawBlock(canvas, reg, sub, margin, y, textW, float64(U)/24, 2, color.RGBA{0xee, 0xee, 0xee, 0xff})
		y -= H * 1 / 100
	}
	if head := strings.TrimSpace(o.Headline); head != "" {
		drawBlock(canvas, bold, head, margin, y, textW, float64(U)/13, 3, color.White)
	}
	return nil
}

// EncodeJPEG encodes a poster for the feed (quality 88 keeps text sharp).
func EncodeJPEG(img image.Image) ([]byte, error) {
	var buf bytes.Buffer
	if err := jpeg.Encode(&buf, img, &jpeg.Options{Quality: 88}); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

// cover scales src to fill dst, cropping the overflow evenly.
func cover(dst *image.RGBA, src image.Image) {
	sb, db := src.Bounds(), dst.Bounds()
	sw, sh := float64(sb.Dx()), float64(sb.Dy())
	scale := maxf(float64(db.Dx())/sw, float64(db.Dy())/sh)
	cw, ch := int(float64(db.Dx())/scale), int(float64(db.Dy())/scale)
	x0 := sb.Min.X + (sb.Dx()-cw)/2
	y0 := sb.Min.Y + (sb.Dy()-ch)/2
	xdraw.CatmullRom.Scale(dst, db, src, image.Rect(x0, y0, x0+cw, y0+ch), draw.Src, nil)
}

// drawBlock draws wrapped text whose last line ends at baselineBottom, shrinking
// the size until it fits in maxLines; it returns the top of the block.
func drawBlock(dst *image.RGBA, f *opentype.Font, text string, x, baselineBottom, width int, size float64, maxLines int, c color.Color) int {
	var lines []string
	var fc font.Face
	for ; size >= 14; size *= 0.9 {
		fc, _ = face(f, size)
		lines = wrap(fc, text, width)
		if len(lines) <= maxLines {
			break
		}
	}
	if len(lines) > maxLines {
		lines = lines[:maxLines]
		lines[maxLines-1] = ellipsize(fc, lines[maxLines-1], width)
	}
	lineH := int(size * 1.18)
	top := baselineBottom - lineH*len(lines)
	d := &font.Drawer{Dst: dst, Src: image.NewUniform(c), Face: fc}
	for i, l := range lines {
		d.Dot = fixed.P(x, top+lineH*(i+1)-int(size*0.22))
		d.DrawString(l)
	}
	return top
}

// drawChip draws a small accent label (the price) ending at bottom.
func drawChip(dst *image.RGBA, f *opentype.Font, text string, x, bottom, unit int, accent color.RGBA) int {
	size := float64(unit) / 20
	fc, _ := face(f, size)
	tw := font.MeasureString(fc, text).Ceil()
	padX, padY := int(size*0.6), int(size*0.35)
	h := int(size) + 2*padY
	r := image.Rect(x, bottom-h, x+tw+2*padX, bottom)
	draw.Draw(dst, r, image.NewUniform(accent), image.Point{}, draw.Src)
	d := &font.Drawer{Dst: dst, Src: image.NewUniform(color.White), Face: fc, Dot: fixed.P(x+padX, bottom-padY-int(size*0.18))}
	d.DrawString(text)
	return r.Min.Y
}

// logoRect is where the logo goes in a top corner: about a sixth of the short side wide, never
// taller than a ninth of the frame, its area capped (logoBox), inside the safe margin.
func logoRect(logo image.Image, corner string, W, H, margin, unit int) image.Rectangle {
	box := logoBox(logo, unit*16/100, H/9)
	lw, lh := box.X, box.Y
	if corner == LogoTopRight {
		return image.Rect(W-margin-lw, margin, W-margin, margin+lh)
	}
	return image.Rect(margin, margin, margin+lw, margin+lh)
}

// logoCorner is the corner the logo goes in: the one asked for, else the calmer top corner of an
// opaque scene (fewer edges and less skin, so the logo never sits on a face or a busy area). Over
// a video overlay the scene is not known here, and the logo goes top left on its plate.
func logoCorner(canvas *image.RGBA, o Overlay, margin, unit int) string {
	if o.LogoCorner == LogoTopLeft || o.LogoCorner == LogoTopRight {
		return o.LogoCorner
	}
	W, H := canvas.Bounds().Dx(), canvas.Bounds().Dy()
	left := logoRect(o.Logo, LogoTopLeft, W, H, margin, unit)
	right := logoRect(o.Logo, LogoTopRight, W, H, margin, unit)
	pad := margin / 2
	l, lok := busyness(canvas, left.Inset(-pad))
	r, rok := busyness(canvas, right.Inset(-pad))
	if lok && rok && r+0.02 < l {
		return LogoTopRight
	}
	return LogoTopLeft
}

// placeLogo draws the logo on its adaptive plate (logo_plate.go) in the corner.
func placeLogo(canvas *image.RGBA, info logoInfo, corner string, margin, unit int, st PlateStyle) {
	W, H := canvas.Bounds().Dx(), canvas.Bounds().Dy()
	drawLogo(canvas, info, logoRect(info.img, corner, W, H, margin, unit), st)
}

// busyness scores how busy an opaque area is (0 calm, about 1 very busy): the mean luma step
// between neighbouring samples plus the share of skin-toned samples, a cheap stand-in for a face.
// It reports false over a transparent canvas.
func busyness(canvas *image.RGBA, r image.Rectangle) (float64, bool) {
	r = r.Intersect(canvas.Bounds())
	if r.Empty() {
		return 0, false
	}
	step := max(1, max(r.Dx(), r.Dy())/40)
	var edges, skin, n float64
	luma := func(c color.RGBA) float64 {
		return (0.2126*float64(c.R) + 0.7152*float64(c.G) + 0.0722*float64(c.B)) / 255
	}
	for y := r.Min.Y; y+step < r.Max.Y; y += step {
		for x := r.Min.X; x+step < r.Max.X; x += step {
			c := canvas.RGBAAt(x, y)
			if c.A < 0xf0 {
				return 0, false
			}
			l := luma(c)
			edges += math.Abs(l-luma(canvas.RGBAAt(x+step, y))) + math.Abs(l-luma(canvas.RGBAAt(x, y+step)))
			if skinTone(c) {
				skin++
			}
			n++
		}
	}
	if n == 0 {
		return 0, false
	}
	return edges/n*2 + skin/n, true
}

// skinTone is the classic RGB skin rule (Kovac et al.), which covers dark and light skin in daylight.
func skinTone(c color.RGBA) bool {
	r, g, b := int(c.R), int(c.G), int(c.B)
	mx, mn := max(r, g, b), min(r, g, b)
	return r > 95 && g > 40 && b > 20 && mx-mn > 15 && r-g > 15 && r > b
}


func wrap(fc font.Face, text string, width int) []string {
	var lines []string
	cur := ""
	for _, w := range strings.Fields(text) {
		next := w
		if cur != "" {
			next = cur + " " + w
		}
		if font.MeasureString(fc, next).Ceil() <= width || cur == "" {
			cur = next
			continue
		}
		lines = append(lines, cur)
		cur = w
	}
	if cur != "" {
		lines = append(lines, cur)
	}
	return lines
}

func ellipsize(fc font.Face, s string, width int) string {
	if font.MeasureString(fc, s).Ceil() <= width {
		return s
	}
	r := []rune(s)
	for len(r) > 1 && font.MeasureString(fc, string(r)+"...").Ceil() > width {
		r = r[:len(r)-1]
	}
	return strings.TrimSpace(string(r)) + "..."
}

func min1(v float64) float64 {
	if v > 1 {
		return 1
	}
	return v
}

func maxf(a, b float64) float64 {
	if a > b {
		return a
	}
	return b
}

// fillRounded fills r with c, its corners rounded by radius.
func fillRounded(dst *image.RGBA, r image.Rectangle, radius int, c color.RGBA) {
	src := image.NewUniform(c)
	for y := r.Min.Y; y < r.Max.Y; y++ {
		inset := 0
		if dy := min(y-r.Min.Y, r.Max.Y-1-y); dy < radius {
			off := radius - dy
			for inset < radius && (radius-inset)*(radius-inset)+off*off > radius*radius {
				inset++
			}
		}
		draw.Draw(dst, image.Rect(r.Min.X+inset, y, r.Max.X-inset, y+1), src, image.Point{}, draw.Over)
	}
}

// AutoLogoCorner is the corner the compositor picks for the logo over this scene.
func AutoLogoCorner(scene image.Image, format string, o Overlay) string {
	size, ok := Formats[format]
	if !ok || o.Logo == nil {
		return LogoTopLeft
	}
	canvas := image.NewRGBA(image.Rect(0, 0, size.X, size.Y))
	if scene != nil {
		cover(canvas, scene)
	}
	U := layoutUnit(size.X, size.Y)
	return logoCorner(canvas, o, U*6/100, U)
}
